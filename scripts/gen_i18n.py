"""Writes the UI message table from i18n/messages.json into src/UCG_Probe.jsx.

The table goes between the `// <UCG_I18N>` and `// </UCG_I18N>` markers inside the core block. All
non-ASCII characters are written as \\uXXXX escapes, so After Effects reads the script correctly
whatever text encoding it assumes for the file.

Usage: python -I -X utf8 scripts/gen_i18n.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'src' / 'UCG_Probe.jsx'
MESSAGES = ROOT / 'i18n' / 'messages.json'
START, END = '// <UCG_I18N>', '// </UCG_I18N>'


def main():
    data = json.loads(MESSAGES.read_text(encoding='utf-8'))
    table = {lang: data[lang] for lang in ('ja', 'en')}
    missing = sorted(set(table['ja']) ^ set(table['en']))
    if missing:
        raise SystemExit('ja/en keys differ: ' + ', '.join(missing))
    body = json.dumps(table, ensure_ascii=True, sort_keys=True, indent=None, separators=(',', ':'))
    block = (START + ' (generated by scripts/gen_i18n.py from i18n/messages.json; do not edit by hand)\n'
             'var UCG_TEXT = ' + body + ';\n' + END)
    text = SRC.read_text(encoding='utf-8')
    if START in text:
        head, rest = text.split(START, 1)
        tail = rest.split(END, 1)[1]
        text = head + block + tail
    else:
        raise SystemExit('markers not found in ' + str(SRC))
    SRC.write_text(text, encoding='utf-8')
    print('wrote', len(table['ja']), 'keys per language into', SRC.name)


if __name__ == '__main__':
    main()
